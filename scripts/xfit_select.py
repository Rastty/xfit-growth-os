#!/usr/bin/env python3
"""Xfit selection engine v0.1 — deterministic product shortlists, NO publication.

Input: normalized catalog generated by xfit_feed_ingest.py.
Output: recommendation candidates with transparent cost metrics, never
commissioned product links until separately verified.

Examples:
  python scripts/xfit_select.py --kind creatine --max-price 700
  python scripts/xfit_select.py --kind whey --max-price 1000

No changes to WordPress, no personal data, no health advice.
"""
import argparse
import json
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

KINDS = {
    "creatine": {"title": ("creatine", "kreatin", "creapure"), "category": ()},
    "whey": {"title": ("whey", "wpc", "wpi", "syrovátkov", "srvatkov"), "category": ("protein",)},
    "plant_protein": {"title": ("vegansk", "vegan", "rastlinn", "rostlinn", "hrachov", "sojov"), "category": ("protein",)},
}
MASS_RE = re.compile(r"(?<![a-z0-9])(\d+(?:[,.]\d+)?)\s*(kg|g)\b", re.I)
MAX_OPTIONS = 20

def mass_grams(title):
    """Return known powder package mass in grams or None; not serving dose."""
    matches = MASS_RE.findall(title)
    if not matches:
        return None
    size, unit = matches[-1]
    number = float(size.replace(",", "."))
    grams = number * (1000 if unit.lower() == "kg" else 1)
    return int(round(grams)) if 50 <= grams <= 10000 else None

def safe_merchant(url):
    p = urlsplit(url or "")
    return p.scheme == "https" and p.hostname in ("namaximum.cz", "www.namaximum.cz") and not p.username and not p.password

def matches_kind(item, kind):
    title = (item.get("title") or "").casefold()
    category = (item.get("category") or "").casefold()
    spec = KINDS[kind]
    if not any(w in title for w in spec["title"]):
        return False
    if spec["category"] and not any(w in category for w in spec["category"]):
        return False
    # No capsules or tablets in gram-weight powder comparisons.
    if any(term in title for term in ("kapsl", "tablet", "capsule")):
        return False
    return True

def select_offers(catalog, kind, max_price=None, min_mass_g=100, limit=12):
    if kind not in KINDS:
        raise ValueError("Unsupported engine kind")
    if not 1 <= limit <= MAX_OPTIONS:
        raise ValueError("limit out of bounds")
    if max_price is not None and max_price <= 0:
        raise ValueError("Invalid price limit")
    if min_mass_g < 50 or min_mass_g > 10000:
        raise ValueError("Invalid minimum mass")
    choices = []
    seen = set()
    for item in catalog.get("products", []):
        if item.get("merchant") != "NaMaximum.cz" or not safe_merchant(item.get("source_url")):
            continue
        if not matches_kind(item, kind):
            continue
        try:
            price = float(item["price_czk"])
        except (ValueError, KeyError, TypeError):
            continue
        if price <= 0 or max_price is not None and price > max_price:
            continue
        mass = mass_grams(item.get("title") or "")
        if mass is None or mass < min_mass_g:
            continue
        key = item.get("ean") or item.get("source_url")
        if key in seen:
            continue
        seen.add(key)
        choices.append({
            "id": str(item.get("id") or ""),
            "title": item["title"],
            "merchant": "NaMaximum.cz",
            "price_czk": round(price, 2),
            "mass_g": mass,
            "price_per_100g_powder_czk": round(price / mass * 100, 2),
            "source_url": item["source_url"],
            "ean": item.get("ean") or "",
            "affiliate_url": None,
            "publish_ready": False,
            "explanation": "Porovnání ceny za hmotnost prášku, nikoli za množství účinné látky či čistých bílkovin."
        })
    choices.sort(key=lambda x: (x["price_per_100g_powder_czk"], x["price_czk"], x["title"]))
    return choices[:limit]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="reports/private-greenmedical-catalog.json")
    ap.add_argument("--kind", choices=KINDS, required=True)
    ap.add_argument("--max-price", type=float)
    ap.add_argument("--min-mass", type=int, default=100)
    ap.add_argument("--limit", type=int, default=12)
    args = ap.parse_args()
    data = json.loads(Path(args.catalog).read_text(encoding="utf-8"))
    items = select_offers(data, args.kind, args.max_price, args.min_mass, args.limit)
    # No full product list to public Actions logs; keep item records in ephemeral runner.
    print(json.dumps({
        "engine": args.kind, "candidate_count": len(items),
        "first_price_per_100g_powder_czk": items[0]["price_per_100g_powder_czk"] if items else None,
        "source": "NaMaximum XML", "affiliate_deeplinks_verified": False,
        "public_site_modified": False,
        "state": "selection_candidates_only"
    }, ensure_ascii=False))
    return 0 if items else 2

if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError, json.JSONDecodeError) as exc:
        print("XFIT_SELECTION_ERROR: " + type(exc).__name__, file=sys.stderr)
        sys.exit(2)
