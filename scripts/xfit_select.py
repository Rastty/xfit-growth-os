#!/usr/bin/env python3
"""Xfit selection engine v0.1 — deterministic product shortlists, NO publication.

Input: normalized catalog generated by xfit_feed_ingest.py.
Output: recommendation candidates with transparent cost metrics, never
commissioned product links until separately verified.

Examples:
  python scripts/xfit_select.py --kind creatine --max-price 700
  python scripts/xfit_select.py --kind whey --max-price 1000

No changes to WordPress, no personal data, no health advice.
"""
import argparse
import json
import math
import re
import sys
import unicodedata
from pathlib import Path
from urllib.parse import urlsplit
from scripts.xfit_availability import delivery_state
from scripts.xfit_feed_ingest import catalog_identity_matches_url

KINDS = {
    "nut_butter": {"title": (), "category": ()},
    "creatine": {"title": ("creatine", "kreatin", "creapure"), "category": ()},
    "whey": {"title": ("whey", "wpc", "wpi", "syrovátkov", "srvatkov"), "category": ("protein",)},
    "plant_protein": {"title": ("vegansk", "vegan", "rastlinn", "rostlinn", "hrachov", "sojov"), "category": ("protein",)},
}
MASS_RE = re.compile(r"(?<![a-z0-9])(\d+(?:[,.]\d+)?)\s*(kg|g)\b", re.I)
# A multipack's single-unit mass must never masquerade as its TOTAL pack mass.
# Without a verified structured pack quantity, reject rather than guess.
MULTIPACK_RE = re.compile(
    r"(?<![a-z0-9])\d{1,3}\s*(?:x|×|\*)\s*(?:\S+\s+){0,3}\d+(?:[,.]\d+)?\s*(?:kg|g)\b", re.I
)
MAX_OPTIONS = 200
# Native publisher scans the *whole* normalized feed before defining the
# cheapest eligible pack. Above this bound, refuse a misleading partial claim.
MAX_FULL_CATALOG_SCAN = 10000

def mass_grams(title):
    """Select only an unambiguous pack mass, never a serving or bundle unit.

    Merchant titles sometimes mention both package weight and a serving size.
    Picking the last number can distort the price-per-100g rank. If multiple
    plausible weights disagree, or a multipack quantity is advertised, fail
    closed until the feed supplies structured pack evidence.
    """
    if not isinstance(title, str) or len(title) > 5000:
        return None
    if MULTIPACK_RE.search(title):
        return None
    matches = MASS_RE.findall(title)
    if not matches:
        return None
    plausible = set()
    for size, unit in matches:
        if len(size) > 14:
            return None
        try:
            number = float(size.replace(",", "."))
        except (ValueError, OverflowError):
            return None
        if not math.isfinite(number):
            return None
        grams = number * (1000 if unit.lower() == "kg" else 1)
        # A 5g scoop can appear alongside a 1kg tub, but is not itself
        # a sellable comparison pack. Never rank 2 plausible pack sizes.
        if 50 <= grams <= 10000:
            plausible.add(int(round(grams)))
    return next(iter(plausible)) if len(plausible) == 1 else None

def safe_merchant(url):
    p = urlsplit(url or "")
    return p.scheme == "https" and p.hostname in ("namaximum.cz", "www.namaximum.cz") and not p.username and not p.password

def folded(value):
    """Accent-insensitive Czech/Slovak matching; retain original source title."""
    return "".join(c for c in unicodedata.normalize("NFKD", value.casefold())
                   if not unicodedata.combining(c))


def plant_powder(item):
    title = folded(item.get("title") or "")
    category = folded(item.get("category") or "")
    # Require explicit protein AND plant identity. A generic vegan supplement,
    # plant extract, flour, bar, capsule or blended dairy powder is not a match.
    protein = bool(re.search(r"\b(?:protein\w*|bilkovin\w*)\b", title))
    plant = bool(re.search(
        r"\b(?:vegan\w*|rostlinn\w*|rastlinn\w*|sojov\w*|soy|"
        r"hrachov\w*|pea|ryzov\w*|rice|konopn\w*|hemp|plant)\b", title))
    category_ok = ("protein" in category or
                   category.strip() in {"rostlinne", "rastlinne", "veganske"})
    banned = ("whey", "syrovatk", "mlecn", "mliecn", "casein", "kasein",
              "collagen", "kolagen", "gainer", "mass gain", "tycink", "bar ",
              "protein bar", "kapsl", "capsul", "tablet", "mouka", "muka",
              "flour", "extrakt", "extract", "creatine", "kreatin",
              "pre-workout", "pre workout", "bcaa", "eaa")
    return protein and plant and category_ok and not any(word in title for word in banned)


def nut_butter(item):
    title = folded(item.get("title") or "")
    category = folded(item.get("category") or "")
    if not re.search(r"\b(?:masla|maslo|masel|nut butter\w*)\b", category):
        return False
    if re.search(r"\b(?:prasek|pras[kc]\w*|powder|olej\w*|oil|tycink\w*|bar|kapsl\w*|tablet\w*|mouka|flour|balicek|set|multipack|aroma|extrakt)\b", title):
        return False
    return bool(re.search(r"\b(?:arasidov\w*|mandlov\w*|kesu|liskov\w*|pistaciov\w*|orechov\w*|peanut|almond|cashew|hazelnut|pistachio|nut)\s+(?:masl\w*|butter\w*)\b",title))


def matches_kind(item, kind):
    if kind == "nut_butter":
        return nut_butter(item)
    if kind == "plant_protein":
        return plant_powder(item)
    title = (item.get("title") or "").casefold()
    category = (item.get("category") or "").casefold()
    spec = KINDS[kind]
    if not any(w in title for w in spec["title"]):
        return False
    if spec["category"] and not any(w in category for w in spec["category"]):
        return False
    # No capsules or tablets in gram-weight powder comparisons.
    if any(term in title for term in ("kapsl", "tablet", "capsule")):
        return False
    return True

def select_offers(catalog, kind, max_price=None, min_mass_g=100, limit=12):
    """Eligible verified powder offers ordered by unit price.

    Bounded ordinary callers receive at most `limit` items. Site publishers
    pass limit=None to examine EVERY eligible offer before deduping flavors
    and choosing both price priorities. Failing on oversized source catalogs
    avoids implying the cheapest candidate was found in a truncated slice.
    """
    if kind not in KINDS:
        raise ValueError("Unsupported engine kind")
    if limit is None:
        raw_items = catalog.get("products", [])
        if not isinstance(raw_items, list) or len(raw_items) > MAX_FULL_CATALOG_SCAN:
            raise ValueError("Complete source catalog too large for safe comparison")
    elif type(limit) is not int or not 1 <= limit <= MAX_OPTIONS:
        raise ValueError("limit out of bounds")
    if max_price is not None:
        if isinstance(max_price, bool):
            raise ValueError("Invalid price limit")
        try:
            max_price = float(max_price)
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError("Invalid price limit") from exc
        if not math.isfinite(max_price) or max_price <= 0:
            raise ValueError("Invalid price limit")
    if min_mass_g < 50 or min_mass_g > 10000:
        raise ValueError("Invalid minimum mass")
    choices = []
    raw_prices = []
    for item in catalog.get("products", []):
        if item.get("merchant") != "NaMaximum.cz" or not safe_merchant(item.get("source_url")):
            continue
        # Defense in depth for independently supplied/previously normalized
        # catalogs: never show a tracked CTA with an invented or mismatched ID.
        if not catalog_identity_matches_url(item.get("id"), item.get("source_url")):
            continue
        availability = delivery_state(item)
        if availability in ("unavailable", "slow_dispatch", "preorder"):
            # Buyer shortlists must not promote known-unavailable offers,
            # preorders or an explicitly quoted >7-day dispatch delay.
            continue
        if not matches_kind(item, kind):
            continue
        if isinstance(item.get("price_czk"), bool):
            continue
        try:
            price = float(item["price_czk"])
        except (ValueError, KeyError, TypeError, OverflowError):
            continue
        if (not math.isfinite(price) or price <= 0 or price > 1000000
                or round(price, 2) <= 0):
            continue
        mass = mass_grams(item.get("title") or "")
        if mass is None:
            continue
        choices.append({
            "id": str(item.get("id") or ""),
            "title": item["title"],
            "merchant": "NaMaximum.cz",
            "price_czk": round(price, 2),
            "mass_g": mass,
            "price_per_100g_powder_czk": round(price / mass * 100, 2),
            "source_url": item["source_url"],
            "ean": item.get("ean") or "",
            "affiliate_url": None,
            "availability_state": availability,
            "publish_ready": False,
            "explanation": ("Porovnání ceny za 100 g celého výrobku, nikoli množství ořechů." if kind == "nut_butter" else "Porovnání ceny za hmotnost prášku, nikoli za množství účinné látky či čistých bílkovin.")
        })
        raw_prices.append(price)
    # Some merchant feeds repeat an EAN, product ID or canonical URL. If the
    # repeated identity disagrees on the variant, package mass or price,
    # neither row is a trustworthy price recommendation. Do not silently pick
    # the first (feed-order dependent), nor the cheapest (possibly stale) row.
    # Only exact identity/price duplicates may be collapsed safely.
    by_identity = {}
    for index, offer in enumerate(choices):
        for field in ("id", "ean", "source_url"):
            value = offer[field]
            if value:
                by_identity.setdefault((field, value), []).append(index)
    ambiguous = set()
    for indices in by_identity.values():
        signatures = {
            (choices[i]["id"], choices[i]["ean"], choices[i]["source_url"],
             choices[i]["mass_g"], choices[i]["price_czk"])
            for i in indices
        }
        if len(signatures) > 1:
            ambiguous.update(indices)

    ranked = sorted(enumerate(choices), key=lambda pair: (
        pair[1]["price_per_100g_powder_czk"], pair[1]["price_czk"],
        pair[1]["title"], pair[1]["id"], pair[1]["source_url"]))
    seen = set()
    unique = []
    for index, offer in ranked:
        if index in ambiguous:
            continue
        identities = {(field, offer[field]) for field in ("id", "ean", "source_url")
                      if offer[field]}
        if identities & seen:
            continue
        seen.update(identities)
        # Apply the user's filters AFTER resolving identity conflicts. A
        # second contradictory row just above a budget or just below the
        # requested minimum mass must still invalidate the purported deal.
        if ((max_price is None or raw_prices[index] <= max_price)
                and offer["mass_g"] >= min_mass_g):
            unique.append(offer)
    return unique if limit is None else unique[:limit]

def choose_price_scenarios(offers, limit=6):
    """Preserve both best per-100g price and lowest eligible upfront cost."""
    if not 2 <= limit <= 12 or len(offers) < 2:
        raise ValueError("Need at least two eligible products and a bounded shortlist")
    unit = lambda o: (o["price_per_100g_powder_czk"], o["price_czk"], o["title"], o["id"])
    upfront = lambda o: (o["price_czk"], o["price_per_100g_powder_czk"], o["title"], o["id"])
    ranked = sorted(offers, key=unit)
    cheapest = min(offers, key=upfront)
    selected = ranked[:limit]
    if cheapest not in selected:
        selected[-1] = cheapest
        selected.sort(key=unit)
    return selected, 0, selected.index(cheapest)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", default="reports/private-greenmedical-catalog.json")
    ap.add_argument("--kind", choices=KINDS, required=True)
    ap.add_argument("--max-price", type=float)
    ap.add_argument("--min-mass", type=int, default=100)
    ap.add_argument("--limit", type=int, default=12)
    args = ap.parse_args()
    data = json.loads(Path(args.catalog).read_text(encoding="utf-8"))
    items = select_offers(data, args.kind, args.max_price, args.min_mass, args.limit)
    # No full product list to public Actions logs; keep item records in ephemeral runner.
    print(json.dumps({
        "engine": args.kind, "candidate_count": len(items),
        "first_price_per_100g_powder_czk": items[0]["price_per_100g_powder_czk"] if items else None,
        "source": "NaMaximum XML", "affiliate_deeplinks_verified": False,
        "public_site_modified": False,
        "state": "selection_candidates_only"
    }, ensure_ascii=False))
    return 0 if items else 2

if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError, json.JSONDecodeError) as exc:
        print("XFIT_SELECTION_ERROR: " + type(exc).__name__, file=sys.stderr)
        sys.exit(2)
